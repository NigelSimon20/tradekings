/**
 * The Google Sheet layout.
 *
 * Columns are matched by header text, not by position, so HR can reorder or
 * insert columns in the sheet without breaking the system. `input` columns are
 * captured by people; `calculated` columns are written back by the system on
 * every system check.
 */
export type InputColumnKey =
  | "id"
  | "employeeId"
  | "employeeName"
  | "employeeEmail"
  | "company"
  | "workerType"
  | "department"
  | "costCentre"
  | "jobTitle"
  | "contractType"
  | "startDate"
  | "endDate"
  | "contractNumber"
  | "renewalStatus"
  | "hrPerson"
  | "hrEmail"
  | "manager"
  | "managerEmail"
  | "location"
  | "notes"
  | "lastUpdated";

export type CalculatedColumnKey =
  | "contractCount"
  | "daysRemaining"
  | "status"
  | "limitStatus"
  | "rehireEligibleDate"
  | "rehireStatus"
  | "flags";

export type ColumnKey = InputColumnKey | CalculatedColumnKey;

export interface SheetColumn {
  key: ColumnKey;
  header: string;
  /** Other header spellings accepted when reading an existing sheet. */
  aliases?: string[];
  kind: "input" | "calculated";
  type: "text" | "date" | "number" | "datetime";
  /** Dropdown values applied by the sheet setup script. */
  options?: readonly string[];
  width?: number;
  note?: string;
}

