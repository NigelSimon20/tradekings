function normaliseHeader(header: string): string {
  return header.toLowerCase().replace(/[^a-z0-9]/g, "");
}

/** Maps each known column to the zero-based index it occupies in the sheet. */
export function buildColumnIndex(headerRow: unknown[]): Map<ColumnKey, number> {
  const byNormalised = new Map<string, number>();
  headerRow.forEach((header, index) => {
    const key = normaliseHeader(String(header ?? ""));
    if (key && !byNormalised.has(key)) byNormalised.set(key, index);
  });

  const index = new Map<ColumnKey, number>();
  for (const column of CONTRACT_COLUMNS) {
    const candidates = [column.header, ...(column.aliases ?? [])];
    for (const candidate of candidates) {
      const position = byNormalised.get(normaliseHeader(candidate));
      if (position !== undefined) {
        index.set(column.key, position);
        break;
      }
    }
  }
  return index;
}

/** Headers from the schema that are missing from the sheet. */
export function missingColumns(headerRow: unknown[]): SheetColumn[] {
  const index = buildColumnIndex(headerRow);
  return CONTRACT_COLUMNS.filter((column) => !index.has(column.key));
}

function cell(row: unknown[], index: Map<ColumnKey, number>, key: ColumnKey): unknown {
  const position = index.get(key);
  return position === undefined ? undefined : row[position];
}

function text(value: unknown): string {
  return value === null || value === undefined ? "" : String(value).trim();
}

function pickOption<T extends string>(value: unknown, options: readonly T[], fallback: T): T {
  const raw = normaliseHeader(text(value));
  if (!raw) return fallback;
  const exact = options.find((option) => normaliseHeader(option) === raw);
  if (exact) return exact;
  const partial = options.find(
    (option) => raw.includes(normaliseHeader(option)) || normaliseHeader(option).includes(raw),
  );
  return partial ?? fallback;
}

export function parseCompany(value: unknown): Company {
  const raw = normaliseHeader(text(value));
  if (raw.startsWith("zim") || raw === "zk") return "Zimkings";
  if (raw.startsWith("trade") || raw === "tk") return "Trade Kings";
  return pickOption(value, COMPANIES, "Trade Kings");
}

export function parseWorkerType(value: unknown): WorkerType {
  const raw = normaliseHeader(text(value));
  if (raw.includes("casual")) return "Casual";
  if (raw.includes("blue")) return "Blue Collar";
  return pickOption(value, WORKER_TYPES, "Blue Collar");
}

export function parseContractType(value: unknown): ContractType {
  return pickOption(value, CONTRACT_TYPES, "New");
}

export function parseRenewalStatus(value: unknown): RenewalStatus {
  return pickOption(value, RENEWAL_STATUSES, "Pending");
}

/** Turns one sheet row into a contract. */
export function parseContractRow(
  row: unknown[],
  index: Map<ColumnKey, number>,
  rowNumber: number,
): Contract {
  const number = Number(text(cell(row, index, "contractNumber")));

  return {
    id: text(cell(row, index, "id")) || `ROW-${rowNumber}`,
    rowNumber,
    employeeId: text(cell(row, index, "employeeId")),
    employeeName: text(cell(row, index, "employeeName")),
    employeeEmail: text(cell(row, index, "employeeEmail")),
    company: parseCompany(cell(row, index, "company")),
    workerType: parseWorkerType(cell(row, index, "workerType")),
    department: text(cell(row, index, "department")),
    costCentre: text(cell(row, index, "costCentre")),
    jobTitle: text(cell(row, index, "jobTitle")),
    contractType: parseContractType(cell(row, index, "contractType")),
    startDate: parseDateValue(cell(row, index, "startDate")),
    endDate: parseDateValue(cell(row, index, "endDate")),
    contractNumber: Number.isFinite(number) && number > 0 ? number : null,
    renewalStatus: parseRenewalStatus(cell(row, index, "renewalStatus")),
    hrPerson: text(cell(row, index, "hrPerson")),
    hrEmail: text(cell(row, index, "hrEmail")),
    manager: text(cell(row, index, "manager")),
    managerEmail: text(cell(row, index, "managerEmail")),
    location: text(cell(row, index, "location")),
    notes: text(cell(row, index, "notes")),
    lastUpdated: parseTimestampValue(cell(row, index, "lastUpdated")),
  };
}

/** True when a sheet row holds nothing we care about. */
export function isBlankRow(row: unknown[]): boolean {
  return !row.some((value) => text(value) !== "");
}

/** The value written to each input column for a contract. */
export function inputCellValue(contract: Contract, key: InputColumnKey): string | number {
  const value = contract[key as keyof Contract];
  if (value === null || value === undefined) return "";
  return typeof value === "number" ? value : String(value);
}

/** The values written back to the calculated columns after a system check. */
export function calculatedCellValues(
  contract: EvaluatedContract,
): Record<CalculatedColumnKey, string | number> {
  const { computed } = contract;
  return {
    contractCount: computed.contractCount,
    daysRemaining: computed.daysRemaining ?? "",
    status: STATUS_META[computed.status].label,
    limitStatus: LIMIT_STATUS_META[computed.limitStatus].label,
    rehireEligibleDate: computed.rehireEligibleDate ?? "",
    rehireStatus: REHIRE_STATUS_META[computed.rehireStatus].label,
    flags: computed.flags.map((flag) => FLAG_META[flag.code].label).join(" • "),
  };
}

/** Column letter for a zero-based index (0 -> A, 26 -> AA). */
export function columnLetter(index: number): string {
  let result = "";
  let current = index;
  while (current >= 0) {
    result = String.fromCharCode((current % 26) + 65) + result;
    current = Math.floor(current / 26) - 1;
  }
  return result;
}

export function describeContractForSheet(contract: EvaluatedContract): string {
  return `${contract.employeeName} (${contract.employeeId}) — ${formatDate(contract.endDate)}`;
}

