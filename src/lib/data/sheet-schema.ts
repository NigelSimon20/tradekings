/** Matches a settings label from the sheet back to its key. */
export function settingKeyFor(label: string): string | null {
  const normalised = normaliseHeader(label);
  return SETTINGS_ROWS.find((row) => normaliseHeader(row.label) === normalised)?.key ?? null;
}

/** Reads "Yes"/"No" style values written by people. */
export function parseSheetBoolean(value: string, fallback: boolean): boolean {
  const text = value.trim().toLowerCase();
  if (!text) return fallback;
  if (["yes", "y", "true", "1", "on"].includes(text)) return true;
  if (["no", "n", "false", "0", "off"].includes(text)) return false;
  return fallback;
}
